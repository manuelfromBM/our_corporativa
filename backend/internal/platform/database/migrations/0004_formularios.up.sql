CREATE TABLE IF NOT EXISTS contactos (
	id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	nombre        TEXT NOT NULL,
	email         TEXT NOT NULL,
	telefono      TEXT NOT NULL,
	tipo_proyecto TEXT NOT NULL,
	mensaje       TEXT NOT NULL,
	creado_en     TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'))
);

CREATE TABLE IF NOT EXISTS participantes_sorteo (
	id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	nombre            TEXT NOT NULL,
	apellido          TEXT NOT NULL,
	correo            TEXT NOT NULL UNIQUE,
	usuario_instagram TEXT NOT NULL,
	tipo_negocio      TEXT NOT NULL,
	nombre_negocio    TEXT NOT NULL,
	comuna            TEXT NOT NULL,
	tiene_sitio_web   BOOLEAN NOT NULL DEFAULT FALSE,
	url_sitio_web     TEXT,
	creado_en         TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'))
);
