CREATE TABLE IF NOT EXISTS members (
	id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	slug       TEXT NOT NULL UNIQUE,
	initials   TEXT NOT NULL,
	img        TEXT NOT NULL,
	alt        TEXT NOT NULL,
	badge      TEXT NOT NULL,
	name       TEXT NOT NULL,
	role       TEXT NOT NULL,
	tech_bio   TEXT NOT NULL,
	biz_bio    TEXT NOT NULL,
	position   INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS member_experience (
	id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	member_id   INTEGER NOT NULL REFERENCES members(id) ON DELETE CASCADE,
	company     TEXT NOT NULL,
	role        TEXT NOT NULL,
	period      TEXT NOT NULL,
	description TEXT NOT NULL,
	position    INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS member_education (
	id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	member_id   INTEGER NOT NULL REFERENCES members(id) ON DELETE CASCADE,
	institution TEXT NOT NULL,
	degree      TEXT NOT NULL,
	period      TEXT NOT NULL,
	position    INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS member_stats (
	id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	member_id INTEGER NOT NULL REFERENCES members(id) ON DELETE CASCADE,
	value     TEXT NOT NULL,
	label     TEXT NOT NULL,
	position  INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS member_skills (
	id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	member_id INTEGER NOT NULL REFERENCES members(id) ON DELETE CASCADE,
	name      TEXT NOT NULL,
	position  INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS member_tools (
	id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	member_id INTEGER NOT NULL REFERENCES members(id) ON DELETE CASCADE,
	name      TEXT NOT NULL,
	position  INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS member_library_categories (
	id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	member_id INTEGER NOT NULL REFERENCES members(id) ON DELETE CASCADE,
	category  TEXT NOT NULL,
	position  INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS member_library_items (
	id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	category_id INTEGER NOT NULL REFERENCES member_library_categories(id) ON DELETE CASCADE,
	name        TEXT NOT NULL,
	position    INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS member_biz_cards (
	id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	member_id   INTEGER NOT NULL REFERENCES members(id) ON DELETE CASCADE,
	icon        TEXT NOT NULL,
	title       TEXT NOT NULL,
	description TEXT NOT NULL,
	position    INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS requerimientos (
	id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	codigo          TEXT NOT NULL UNIQUE,
	servicio_slug   TEXT NOT NULL,
	servicio_titulo TEXT NOT NULL,
	nombre          TEXT NOT NULL,
	correo          TEXT NOT NULL,
	telefono        TEXT NOT NULL,
	empresa         TEXT NOT NULL,
	medio_preferido TEXT NOT NULL,
	es_sorteo       BOOLEAN NOT NULL DEFAULT FALSE,
	enviado_en      TEXT NOT NULL,
	creado_en       TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'))
);

CREATE TABLE IF NOT EXISTS requerimiento_respuestas (
	id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	requerimiento_id INTEGER NOT NULL REFERENCES requerimientos(id) ON DELETE CASCADE,
	seccion_id       TEXT NOT NULL,
	seccion_titulo   TEXT NOT NULL,
	campo_id         TEXT NOT NULL,
	pregunta         TEXT NOT NULL,
	respuesta        TEXT NOT NULL,
	position         INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_requerimiento_respuestas_req ON requerimiento_respuestas(requerimiento_id);
