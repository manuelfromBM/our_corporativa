CREATE TABLE IF NOT EXISTS miembros (
	id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	slug              TEXT NOT NULL UNIQUE,
	iniciales         TEXT NOT NULL,
	imagen            TEXT NOT NULL,
	texto_alternativo TEXT NOT NULL,
	insignia          TEXT NOT NULL,
	nombre            TEXT NOT NULL,
	cargo             TEXT NOT NULL,
	bio_tecnica       TEXT NOT NULL,
	bio_negocio       TEXT NOT NULL,
	posicion          INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS miembro_experiencias (
	id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	miembro_id  INTEGER NOT NULL REFERENCES miembros(id) ON DELETE CASCADE,
	empresa     TEXT NOT NULL,
	cargo       TEXT NOT NULL,
	periodo     TEXT NOT NULL,
	descripcion TEXT NOT NULL,
	posicion    INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS miembro_estudios (
	id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	miembro_id  INTEGER NOT NULL REFERENCES miembros(id) ON DELETE CASCADE,
	institucion TEXT NOT NULL,
	titulo      TEXT NOT NULL,
	periodo     TEXT NOT NULL,
	posicion    INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS miembro_estadisticas (
	id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	miembro_id INTEGER NOT NULL REFERENCES miembros(id) ON DELETE CASCADE,
	valor      TEXT NOT NULL,
	etiqueta   TEXT NOT NULL,
	posicion   INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS miembro_habilidades (
	id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	miembro_id INTEGER NOT NULL REFERENCES miembros(id) ON DELETE CASCADE,
	nombre     TEXT NOT NULL,
	posicion   INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS miembro_herramientas (
	id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	miembro_id INTEGER NOT NULL REFERENCES miembros(id) ON DELETE CASCADE,
	nombre     TEXT NOT NULL,
	posicion   INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS miembro_categorias_librerias (
	id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	miembro_id INTEGER NOT NULL REFERENCES miembros(id) ON DELETE CASCADE,
	categoria  TEXT NOT NULL,
	posicion   INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS miembro_librerias (
	id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	categoria_id INTEGER NOT NULL REFERENCES miembro_categorias_librerias(id) ON DELETE CASCADE,
	nombre       TEXT NOT NULL,
	posicion     INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS miembro_tarjetas_negocio (
	id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	miembro_id  INTEGER NOT NULL REFERENCES miembros(id) ON DELETE CASCADE,
	icono       TEXT NOT NULL,
	titulo      TEXT NOT NULL,
	descripcion TEXT NOT NULL,
	posicion    INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS requerimientos (
	id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	codigo          TEXT NOT NULL UNIQUE,
	servicio_slug   TEXT NOT NULL,
	servicio_titulo TEXT NOT NULL,
	nombre          TEXT NOT NULL,
	correo          TEXT NOT NULL,
	telefono        TEXT NOT NULL,
	empresa         TEXT NOT NULL,
	medio_preferido TEXT NOT NULL,
	es_sorteo       BOOLEAN NOT NULL DEFAULT FALSE,
	enviado_en      TEXT NOT NULL,
	creado_en       TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'))
);

CREATE TABLE IF NOT EXISTS requerimiento_respuestas (
	id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	requerimiento_id INTEGER NOT NULL REFERENCES requerimientos(id) ON DELETE CASCADE,
	seccion_id       TEXT NOT NULL,
	seccion_titulo   TEXT NOT NULL,
	campo_id         TEXT NOT NULL,
	pregunta         TEXT NOT NULL,
	respuesta        TEXT NOT NULL,
	posicion         INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_requerimiento_respuestas_req ON requerimiento_respuestas(requerimiento_id);
