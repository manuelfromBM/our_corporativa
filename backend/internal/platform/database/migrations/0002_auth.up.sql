CREATE TABLE users (
	id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	email         TEXT NOT NULL UNIQUE,
	name          TEXT NOT NULL,
	-- NULL mientras la persona no active su invitación.
	password_hash TEXT,
	role          TEXT NOT NULL CHECK (role IN ('cliente', 'integrante', 'admin')),
	active        BOOLEAN NOT NULL DEFAULT TRUE,
	member_id     INTEGER REFERENCES members(id) ON DELETE SET NULL,
	created_at    TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')),
	updated_at    TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'))
);

CREATE TABLE sessions (
	id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	token_hash TEXT NOT NULL UNIQUE,
	expires_at TEXT NOT NULL,
	created_at TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'))
);

CREATE INDEX idx_sessions_user ON sessions(user_id);
CREATE INDEX idx_sessions_expires ON sessions(expires_at);

-- Tokens de un solo uso para activar una invitación o recuperar la contraseña.
CREATE TABLE user_tokens (
	id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	purpose    TEXT NOT NULL CHECK (purpose IN ('invitacion', 'recuperacion')),
	token_hash TEXT NOT NULL UNIQUE,
	expires_at TEXT NOT NULL,
	used_at    TEXT,
	created_at TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'))
);

CREATE INDEX idx_user_tokens_user ON user_tokens(user_id);

-- Intentos por clave (ej: "login:correo"), para limitar la fuerza bruta.
CREATE TABLE auth_attempts (
	id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	key          TEXT NOT NULL,
	attempted_at TEXT NOT NULL
);

CREATE INDEX idx_auth_attempts_key ON auth_attempts(key, attempted_at);
