CREATE TABLE usuarios (
	id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	correo           TEXT NOT NULL UNIQUE,
	nombre           TEXT NOT NULL,
	-- NULL mientras la persona no active su invitación.
	hash_contrasena  TEXT,
	rol              TEXT NOT NULL CHECK (rol IN ('cliente', 'integrante', 'admin')),
	activo           BOOLEAN NOT NULL DEFAULT TRUE,
	miembro_id       INTEGER REFERENCES miembros(id) ON DELETE SET NULL,
	creado_en        TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')),
	actualizado_en   TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'))
);

CREATE TABLE sesiones (
	id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
	hash_token TEXT NOT NULL UNIQUE,
	expira_en  TEXT NOT NULL,
	creado_en  TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'))
);

CREATE INDEX idx_sesiones_usuario ON sesiones(usuario_id);
CREATE INDEX idx_sesiones_expira ON sesiones(expira_en);

-- Tokens de un solo uso para activar una invitación o recuperar la contraseña.
CREATE TABLE tokens_usuario (
	id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
	proposito  TEXT NOT NULL CHECK (proposito IN ('invitacion', 'recuperacion')),
	hash_token TEXT NOT NULL UNIQUE,
	expira_en  TEXT NOT NULL,
	usado_en   TEXT,
	creado_en  TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'))
);

CREATE INDEX idx_tokens_usuario_usuario ON tokens_usuario(usuario_id);

-- Intentos por clave (ej: "login:correo"), para limitar la fuerza bruta.
CREATE TABLE intentos_acceso (
	id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	clave        TEXT NOT NULL,
	intentado_en TEXT NOT NULL
);

CREATE INDEX idx_intentos_acceso_clave ON intentos_acceso(clave, intentado_en);
