CREATE TABLE clients (
	id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name         TEXT NOT NULL,
	contact_name TEXT NOT NULL DEFAULT '',
	email        TEXT NOT NULL DEFAULT '',
	phone        TEXT NOT NULL DEFAULT '',
	created_at   TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')),
	updated_at   TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'))
);

CREATE TABLE client_users (
	client_id INTEGER NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
	user_id   INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	PRIMARY KEY (client_id, user_id)
);

CREATE INDEX idx_client_users_user ON client_users(user_id);

CREATE TABLE projects (
	id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	client_id      INTEGER NOT NULL REFERENCES clients(id) ON DELETE RESTRICT,
	request_id     INTEGER REFERENCES requerimientos(id) ON DELETE SET NULL,
	name           TEXT NOT NULL,
	service_slug   TEXT NOT NULL DEFAULT '',
	description    TEXT NOT NULL DEFAULT '',
	internal_notes TEXT NOT NULL DEFAULT '',
	status         TEXT NOT NULL DEFAULT 'por_iniciar' CHECK (status IN (
		'por_iniciar', 'levantamiento', 'diseno', 'desarrollo', 'revision', 'entregado', 'pausado'
	)),
	progress       INTEGER NOT NULL DEFAULT 0 CHECK (progress BETWEEN 0 AND 100),
	started_on     TEXT,
	due_on         TEXT,
	created_at     TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')),
	updated_at     TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'))
);

CREATE INDEX idx_projects_client ON projects(client_id);
-- Una solicitud solo se convierte una vez en proyecto.
CREATE UNIQUE INDEX idx_projects_request ON projects(request_id) WHERE request_id IS NOT NULL;

CREATE TABLE project_milestones (
	id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	project_id   INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
	title        TEXT NOT NULL,
	description  TEXT NOT NULL DEFAULT '',
	status       TEXT NOT NULL DEFAULT 'pendiente' CHECK (status IN ('pendiente', 'en_curso', 'completado')),
	due_on       TEXT,
	completed_on TEXT,
	position     INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX idx_project_milestones_project ON project_milestones(project_id);

-- Los avances nacen ocultos: el cliente solo ve lo que el equipo decide publicar.
CREATE TABLE project_updates (
	id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	project_id        INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
	author_id         INTEGER REFERENCES users(id) ON DELETE SET NULL,
	title             TEXT NOT NULL,
	body              TEXT NOT NULL DEFAULT '',
	visible_to_client BOOLEAN NOT NULL DEFAULT FALSE,
	created_at        TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'))
);

CREATE INDEX idx_project_updates_project ON project_updates(project_id);
