CREATE TABLE clientes (
	id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	nombre          TEXT NOT NULL,
	nombre_contacto TEXT NOT NULL DEFAULT '',
	correo          TEXT NOT NULL DEFAULT '',
	telefono        TEXT NOT NULL DEFAULT '',
	creado_en       TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')),
	actualizado_en  TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'))
);

CREATE TABLE cliente_usuarios (
	cliente_id INTEGER NOT NULL REFERENCES clientes(id) ON DELETE CASCADE,
	usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
	PRIMARY KEY (cliente_id, usuario_id)
);

CREATE INDEX idx_cliente_usuarios_usuario ON cliente_usuarios(usuario_id);

CREATE TABLE proyectos (
	id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	cliente_id       INTEGER NOT NULL REFERENCES clientes(id) ON DELETE RESTRICT,
	requerimiento_id INTEGER REFERENCES requerimientos(id) ON DELETE SET NULL,
	nombre           TEXT NOT NULL,
	servicio_slug    TEXT NOT NULL DEFAULT '',
	descripcion      TEXT NOT NULL DEFAULT '',
	notas_internas   TEXT NOT NULL DEFAULT '',
	estado           TEXT NOT NULL DEFAULT 'por_iniciar' CHECK (estado IN (
		'por_iniciar', 'levantamiento', 'diseno', 'desarrollo', 'revision', 'entregado', 'pausado'
	)),
	avance           INTEGER NOT NULL DEFAULT 0 CHECK (avance BETWEEN 0 AND 100),
	fecha_inicio     TEXT,
	fecha_entrega    TEXT,
	creado_en        TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')),
	actualizado_en   TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'))
);

CREATE INDEX idx_proyectos_cliente ON proyectos(cliente_id);
-- Una solicitud solo se convierte una vez en proyecto.
CREATE UNIQUE INDEX idx_proyectos_requerimiento ON proyectos(requerimiento_id) WHERE requerimiento_id IS NOT NULL;

CREATE TABLE proyecto_hitos (
	id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	proyecto_id      INTEGER NOT NULL REFERENCES proyectos(id) ON DELETE CASCADE,
	titulo           TEXT NOT NULL,
	descripcion      TEXT NOT NULL DEFAULT '',
	estado           TEXT NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente', 'en_curso', 'completado')),
	fecha_limite     TEXT,
	fecha_completado TEXT,
	posicion         INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX idx_proyecto_hitos_proyecto ON proyecto_hitos(proyecto_id);

-- Los avances nacen ocultos: el cliente solo ve lo que el equipo decide publicar.
CREATE TABLE proyecto_avances (
	id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	proyecto_id        INTEGER NOT NULL REFERENCES proyectos(id) ON DELETE CASCADE,
	autor_id           INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
	titulo             TEXT NOT NULL,
	contenido          TEXT NOT NULL DEFAULT '',
	visible_al_cliente BOOLEAN NOT NULL DEFAULT FALSE,
	creado_en          TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'))
);

CREATE INDEX idx_proyecto_avances_proyecto ON proyecto_avances(proyecto_id);
